// Records a store release as a migration, so the usual `yarn db:migrate` run
// against prod publishes it to the /v1/app-version endpoint and the app shows
// its update banner. Run after the store rollout is live, or pass --released-at.
//
//   yarn release:app 1.0.8
//   yarn release:app 1.0.8 --platform ios --min-supported 1.0.5 --released-at 2026-11-01T08:00:00Z

import { execSync } from "child_process";
import { readdirSync, writeFileSync } from "fs";
import { join } from "path";

const PLATFORMS = ["ios", "android"] as const;
type Platform = (typeof PLATFORMS)[number];

const SEMVER = /^\d+\.\d+\.\d+$/;
const MIGRATIONS_DIR = join(__dirname, "..", "drizzle", "migrations");

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function parseArgs(argv: string[]) {
  const [version, ...rest] = argv;
  if (!version || !SEMVER.test(version)) {
    fail("Usage: yarn release:app <x.y.z> [--platform ios|android] [--min-supported x.y.z] [--released-at <ISO date>]");
  }

  let platforms: readonly Platform[] = PLATFORMS;
  let minSupported: string | null = null;
  let releasedAt: string | null = null;

  for (let i = 0; i < rest.length; i += 2) {
    const flag = rest[i];
    const value = rest[i + 1];
    if (value === undefined) fail(`Missing value for ${flag}`);
    switch (flag) {
      case "--platform":
        if (!PLATFORMS.includes(value as Platform)) fail(`--platform must be one of ${PLATFORMS.join(", ")}`);
        platforms = [value as Platform];
        break;
      case "--min-supported":
        if (!SEMVER.test(value)) fail("--min-supported must be x.y.z");
        minSupported = value;
        break;
      case "--released-at":
        if (Number.isNaN(Date.parse(value))) fail("--released-at must be an ISO date");
        releasedAt = new Date(value).toISOString();
        break;
      default:
        fail(`Unknown option ${flag}`);
    }
  }

  return { version, platforms, minSupported, releasedAt };
}

function sqlLiteral(value: string | null) {
  return value === null ? "NULL" : `'${value}'`;
}

const { version, platforms, minSupported, releasedAt } = parseArgs(process.argv.slice(2));
const name = `app_release_${version.replace(/\./g, "_")}`;

const before = new Set(readdirSync(MIGRATIONS_DIR));
execSync(`yarn drizzle-kit generate --custom --name ${name}`, { stdio: "inherit" });
const created = readdirSync(MIGRATIONS_DIR).filter((dir) => !before.has(dir) && dir.endsWith(`_${name}`));
if (created.length !== 1) fail(`Expected one new migration folder for ${name}, found ${created.length}`);

const rows = platforms
  .map(
    (platform) =>
      `  ('${platform}', '${version}', ${sqlLiteral(minSupported)}, ${releasedAt ? `'${releasedAt}'` : "now()"})`
  )
  .join(",\n");
const sql = `-- App release ${version} for ${platforms.join(", ")}, generated by yarn release:app
INSERT INTO app_releases (platform, version, min_supported_version, released_at)
VALUES
${rows}
ON CONFLICT (platform, version) DO NOTHING;
`;

const file = join(MIGRATIONS_DIR, created[0], "migration.sql");
writeFileSync(file, sql);
console.log(`Wrote ${file}`);
console.log("Commit it and run the migration against prod once the store rollout is live.");
